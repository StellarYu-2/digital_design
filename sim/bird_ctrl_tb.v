`timescale 1ns / 1ps

module bird_ctrl_tb();

    // ---------------------------------------------------------
    // 信号定义
    // ---------------------------------------------------------
    reg         clk;
    reg         rst_n;
    reg         key_jump;
    reg         ai_jump;
    reg         auto_mode;
    reg         game_active;
    reg         frame_en_unused;

    wire [11:0] bird_y;
    wire [11:0] bird_x;
    wire [9:0]  bird_angle;

    // ---------------------------------------------------------
    // 例化待测设计 (DUT)
    // ---------------------------------------------------------
    bird_ctrl u_bird_ctrl (
        .clk             (clk),
        .rst_n           (rst_n),
        .key_jump        (key_jump),
        .ai_jump         (ai_jump),
        .auto_mode       (auto_mode),
        .game_active     (game_active),
        .frame_en_unused (frame_en_unused),
        .bird_y          (bird_y),
        .bird_x          (bird_x),
        .bird_angle      (bird_angle)
    );

    // ---------------------------------------------------------
    // 时钟生成：65MHz (周期约 15.38ns)
    // ---------------------------------------------------------
    initial clk = 0;
    always #7.69 clk = ~clk;

    // ---------------------------------------------------------
    // 激励产生
    // ---------------------------------------------------------
    initial begin
        // 1. 信号初始化 & 系统复位
        rst_n           = 0;
        key_jump        = 0;
        ai_jump         = 0;
        auto_mode       = 0;
        game_active     = 0;
        frame_en_unused = 0;

        #100;
        rst_n = 1;      // 释放复位
        #100;

        // =========================================================
        // 阶段一：前 1/5 时间 (200ms) —— 纯自由下落模拟
        // =========================================================
        game_active = 1;
        // 等待 200ms (约 12 帧)。小鸟 Y 坐标会从 384 加速增加到 460 左右
        #200_000_000; 

        // =========================================================
        // 阶段二：后 4/5 时间 (800ms) —— 两次完整的跳跃模拟
        // =========================================================
        
        // --- 第 1 次跳跃 (手动跳跃，分配 400ms) ---
        key_jump = 1;
        #100_000;       
        key_jump = 0;
        
        // 等待 400ms (约 24 帧)。你会看到一个完美的完整抛物线 (上升12帧，下降12帧)
        #400_000_000;

        // --- 切换到 AI 自动模式 ---
        auto_mode = 1;
        #10_000_000; // 留一点小间隔切换状态

        // --- 第 2 次跳跃 (AI跳跃，分配 400ms) ---
        ai_jump = 1;
        #100_000;       
        ai_jump = 0;

        // 再次等待 400ms 观察完整抛物线
        #400_000_000;

        // =========================================================
        // 仿真结束
        // =========================================================
        game_active = 0;
        #20_000_000; // 游戏结束后再稍微跑一点点看复位状态

        $display("Simulation Finished!");
        $stop;  // 暂停仿真，保留在波形界面，不弹窗
    end

endmodule