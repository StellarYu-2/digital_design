`timescale 1ns / 1ps

module collision_det_tb();

    // ---------------------------------------------------------
    // 信号定义
    // ---------------------------------------------------------
    reg         clk;
    reg         rst_n;
    
    reg  [11:0] bird_y;
    reg  [11:0] bird_x;
    reg  [11:0] pipe1_x;
    reg  [11:0] pipe1_gap_y;
    reg  [11:0] pipe2_x;
    reg  [11:0] pipe2_gap_y;
    
    wire        collision;

    // ---------------------------------------------------------
    // 例化待测设计 (DUT)
    // ---------------------------------------------------------
    collision_det u_collision_det (
        .clk         (clk),
        .rst_n       (rst_n),
        .bird_y      (bird_y),
        .bird_x      (bird_x),
        .pipe1_x     (pipe1_x),
        .pipe1_gap_y (pipe1_gap_y),
        .pipe2_x     (pipe2_x),
        .pipe2_gap_y (pipe2_gap_y),
        .collision   (collision)
    );

    // ---------------------------------------------------------
    // 时钟生成
    // ---------------------------------------------------------
    initial clk = 0;
    always #10 clk = ~clk; // 简单给个 20ns 周期即可

    // ---------------------------------------------------------
    // 激励产生：模拟 5 种不同场景
    // ---------------------------------------------------------
    initial begin
        // --- 初始化状态 (安全飞行) ---
        rst_n       = 0;
        bird_x      = 300;   // 小鸟固定在屏幕左侧 x=300
        bird_y      = 384;   // 屏幕中央
        pipe1_x     = 1000;  // 管道在很远的地方
        pipe1_gap_y = 384;
        pipe2_x     = 1500;
        pipe2_gap_y = 384;

        #50;
        rst_n = 1;
        #50;

        // ==========================================
        // 场景 1：撞击天花板 (Y <= 0)
        // ==========================================
        bird_y = 0;  
        #40; // 等待两个时钟周期，观察 collision 拉高
        bird_y = 384; // 恢复安全高度
        #40;

        // ==========================================
        // 场景 2：撞击地面 (Y >= 668 - 35 = 633)
        // ==========================================
        bird_y = 635; 
        #40;
        bird_y = 384; 
        #40;

        // ==========================================
        // 场景 3：撞击管道1的【上管】
        // ==========================================
        // 管道开口在 384。上管底部边缘 = 384 - (220/2) = 274
        // 只要小鸟的 Y + 5 < 274，就会撞上
        pipe1_x = 280; // 把管道1瞬间移到小鸟身上 (小鸟宽50, 发生X轴重叠)
        bird_y  = 200; // 小鸟飞得太高，撞到上管
        #40;
        bird_y  = 384; // 小鸟回到缝隙中间
        pipe1_x = 1000;// 移开管道
        #40;

        // ==========================================
        // 场景 4：撞击管道2的【下管】
        // ==========================================
        // 管道开口在 300。下管顶部边缘 = 300 + (220/2) = 410
        // 小鸟底部 = Y + 35。只要 Y + 35 - 5 > 410，即 Y > 380，就会撞下管
        pipe2_x = 280; // 管道2和小鸟X轴重叠
        bird_y  = 400; // 小鸟飞得太低，鸟脚刮到下管
        #40;
        bird_y  = 300; // 小鸟回到缝隙中间
        pipe2_x = 1500;
        #40;

        // ==========================================
        // 场景 5：完美穿过管道 (无碰撞)
        // ==========================================
        pipe1_x = 300; // 管道1来到小鸟身上
        pipe1_gap_y = 384;
        bird_y = 370;  // 小鸟稳稳地处于开口中心区域 (274 ~ 494之间)
        #60;

        $display("Simulation Finished!");
        $stop;
    end

endmodule